#!/usr/bin/env python3
"""Generate WebAssetsGz.h from WebPage.h, WebCss.h and WebJs.h.

Run this after editing any of the web asset headers:

    python3 tools/pack_web_assets.py

The firmware checks the raw lengths stored here before using a gzip blob. If a
header changed without regenerating this file, the clock serves the raw asset
instead of a stale compressed copy.
"""
import gzip
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def raw_string(path: Path, delimiter: str) -> bytes:
    text = path.read_text(encoding="utf-8")
    match = re.search(r'R"' + delimiter + r'\((.*)\)' + delimiter + r'"', text, re.S)
    if not match:
        raise SystemExit(f"raw string not found in {path}")
    return match.group(1).encode("utf-8")


def c_array(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return (
        f"static const uint8_t {name}[] PROGMEM = {{\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const size_t {name}_LEN = sizeof({name});\n"
    )


def main() -> None:
    assets = [
        ("WEB_HTML", raw_string(ROOT / "WebPage.h", "HTMLPAGE")),
        ("WEB_CSS", raw_string(ROOT / "WebCss.h", "CSSCONTENT")),
        ("WEB_JS", raw_string(ROOT / "WebJs.h", "JSCONTENT")),
    ]
    out = [
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "// Generated by tools/pack_web_assets.py - do not edit by hand.",
        "",
    ]
    for name, raw in assets:
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        out.append(f"static const size_t {name}_RAW_LEN = {len(raw)};")
        out.append(c_array(name + "_GZ", gz))
        print(f"{name}: {len(raw)} -> {len(gz)} bytes")
    (ROOT / "WebAssetsGz.h").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
